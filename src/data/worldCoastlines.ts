export const WORLD_LANDMASS_PATHS: string[] = LANDMASS_POLYGONS.map((polygon) => {
  return (
    polygon
      .map(([lon, lat], idx) => {
        const [x, y] = projectLonLat(lon, lat);
        return `${idx === 0 ? 'M' : 'L'}${x.toFixed(1)},${y.toFixed(1)}`;
      })
      .join(' ') + ' Z'
  );
});
