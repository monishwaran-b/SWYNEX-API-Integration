export const MAP_WIDTH = 1000;
export const MAP_HEIGHT = 500;

export function projectLonLat(lon: number, lat: number): [number, number] {
  const clampedLon = Math.max(-180, Math.min(180, lon));
  const clampedLat = Math.max(-85, Math.min(85, lat));
  const x = ((clampedLon + 180) / 360) * MAP_WIDTH;
  const y = ((90 - clampedLat) / 180) * MAP_HEIGHT;
  return [x, y];
}

export function unprojectPoint(x: number, y: number): { lon: number; lat: number } {
  const lon = (x / MAP_WIDTH) * 360 - 180;
  const lat = 90 - (y / MAP_HEIGHT) * 180;
  return {
    lon: Math.max(-180, Math.min(180, lon)),
    lat: Math.max(-90, Math.min(90, lat)),
  };
}

